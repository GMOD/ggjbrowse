#!/usr/bin/env bash
# Compares each file this repo copies from GMOD/ggbandage with its source:
#   scripts/check-standalone.sh               against the commit its header names
#   scripts/check-standalone.sh --latest      also, whether ggbandage's main has moved past it
#   scripts/check-standalone.sh --update REF  rewrites every copy from ggbandage at REF
# A copy is its source with a five-line header naming it, as
# usethis::use_standalone() writes.
set -euo pipefail
cd "$(dirname "$0")/.."

REPO=GMOD/ggbandage
declare -A SOURCES=(
  [R/import-standalone-v8-host.R]=R/standalone-v8-host.R
)

raw() { curl -fsSL "https://raw.githubusercontent.com/$REPO/$1/$2"; }

header() {
  local copy=$1 ref=$2 path=$3 c='#' by
  case $copy in
    *.R)
      local name=${path#R/standalone-}
      by="usethis::use_standalone(\"$REPO\", \"${name%.R}\", ref = \"$ref\")"
      ;;
    *)
      c=//
      by="scripts/check-standalone.sh --update $ref"
      ;;
  esac
  printf '%s Standalone file: do not edit by hand\n' "$c"
  printf '%s Source: https://github.com/%s/blob/%s/%s\n' "$c" "$REPO" "$ref" "$path"
  printf '%s Generated by: %s\n' "$c" "$by"
  printf '%s %s\n' "$c" "$(printf -- '-%.0s' {1..70})"
  printf '%s\n' "$c"
}

if [ "${1:-}" = --update ]; then
  ref=${2:?give the ggbandage commit to copy from}
  for copy in "${!SOURCES[@]}"; do
    { header "$copy" "$ref" "${SOURCES[$copy]}"; raw "$ref" "${SOURCES[$copy]}"; } >"$copy"
  done
  exit
fi

status=0
for copy in "${!SOURCES[@]}"; do
  path=${SOURCES[$copy]}
  ref=$(sed -n "2s|.*/blob/\([^/]*\)/.*|\1|p" "$copy")
  if ! diff -u <(raw "$ref" "$path") <(tail -n +6 "$copy"); then
    echo "$copy differs from $REPO's $path at $ref" >&2
    status=1
  fi
  if [ "${1:-}" = --latest ] && ! diff -q <(raw "$ref" "$path") <(raw main "$path") >/dev/null; then
    echo "$REPO's main has changed $path since $ref: run scripts/check-standalone.sh --update <sha>" >&2
    status=1
  fi
done
exit $status
